-- ------------------------------------------------------------------------------
-- 1. DEPOTS TABLE (KSRTC 97 Depots Master Dataset - IDs 1..97)
-- ------------------------------------------------------------------------------
CREATE TABLE public.depots (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    depot_code TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    mobile TEXT,
    head_phone TEXT,
    email TEXT,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 2. PROFILES TABLE (Linked to Supabase auth.users & integer depot_id)
-- ------------------------------------------------------------------------------
CREATE TABLE public.profiles (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    auth_user_id UUID UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    phone TEXT NOT NULL,
    email TEXT,
    role TEXT NOT NULL DEFAULT 'USER' CHECK (role IN ('USER', 'DEPOT_HEAD', 'ADMIN')),
    depot_id INT REFERENCES public.depots(id) ON DELETE SET NULL,
    active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 3. BUSES TABLE (KSRTC Bus Fleet Master Data)
-- ------------------------------------------------------------------------------
CREATE TABLE public.buses (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bus_number TEXT NOT NULL,
    registration_number TEXT NOT NULL UNIQUE,
    depot_id INT REFERENCES public.depots(id) ON DELETE CASCADE,
    bus_type TEXT DEFAULT 'Super Fast',
    status TEXT DEFAULT 'ACTIVE',
    data_source TEXT DEFAULT 'MOCK',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 4. ROUTES TABLE (KSRTC Bus Routes Master Data)
-- ------------------------------------------------------------------------------
CREATE TABLE public.routes (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_code TEXT NOT NULL UNIQUE,
    source TEXT NOT NULL,
    destination TEXT NOT NULL,
    depot_id INT REFERENCES public.depots(id) ON DELETE CASCADE,
    estimated_duration TEXT,
    status TEXT DEFAULT 'ACTIVE',
    data_source TEXT DEFAULT 'MOCK',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 5. ROUTE STOPS TABLE
-- ------------------------------------------------------------------------------
CREATE TABLE public.route_stops (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id INT REFERENCES public.routes(id) ON DELETE CASCADE,
    stop_name TEXT NOT NULL,
    stop_sequence INT NOT NULL,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 6. CONDUCTORS TABLE (KSRTC Staff Master Data)
-- ------------------------------------------------------------------------------
CREATE TABLE public.conductors (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pen TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    phone TEXT NOT NULL,
    email TEXT,
    depot_id INT REFERENCES public.depots(id) ON DELETE CASCADE,
    status TEXT DEFAULT 'ACTIVE',
    data_source TEXT DEFAULT 'MOCK',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 7. DUTY ASSIGNMENTS TABLE (Bus + Route + Conductor Shifts)
-- ------------------------------------------------------------------------------
CREATE TABLE public.duty_assignments (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bus_id INT REFERENCES public.buses(id) ON DELETE CASCADE,
    route_id INT REFERENCES public.routes(id) ON DELETE CASCADE,
    conductor_id INT REFERENCES public.conductors(id) ON DELETE CASCADE,
    depot_id INT REFERENCES public.depots(id) ON DELETE CASCADE,
    duty_date DATE NOT NULL DEFAULT CURRENT_DATE,
    shift_start TIME NOT NULL,
    shift_end TIME NOT NULL,
    trip_number INT DEFAULT 1,
    status TEXT DEFAULT 'ASSIGNED',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 8. COMPLAINTS TABLE (UUID Identifier Core Grievance Record)
-- ------------------------------------------------------------------------------
