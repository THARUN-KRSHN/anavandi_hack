-- ==============================================================================
-- AUTOMATIC PROFILE CREATION TRIGGER FOR SUPABASE AUTH SIGNUPS
-- ==============================================================================

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.profiles (auth_user_id, name, phone, email, role, active)
    VALUES (
        NEW.id,
        COALESCE(NEW.raw_user_meta_data->>'name', NEW.phone, NEW.email, 'User'),
        COALESCE(NEW.phone, NEW.raw_user_meta_data->>'phone', ''),
        COALESCE(NEW.email, CONCAT('user_', SUBSTRING(NEW.id::text, 1, 8), '@bussahayi.org')),
        COALESCE(UPPER(NEW.raw_user_meta_data->>'role'), 'USER'),
        TRUE
    )
    ON CONFLICT (auth_user_id) DO UPDATE SET
        name = EXCLUDED.name,
        phone = EXCLUDED.phone,
        email = EXCLUDED.email;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- BACKFILL PROFILES FOR EXISTING AUTH USERS
INSERT INTO public.profiles (auth_user_id, name, phone, email, role)
SELECT 
    id,
    COALESCE(raw_user_meta_data->>'name', phone, email, 'User'),
    COALESCE(phone, raw_user_meta_data->>'phone', ''),
    COALESCE(email, CONCAT('user_', SUBSTRING(id::text, 1, 8), '@bussahayi.org')),
    COALESCE(UPPER(raw_user_meta_data->>'role'), 'USER')
FROM auth.users
ON CONFLICT (auth_user_id) DO NOTHING;

