-- PUBLIC READ POLICIES (Master Data)
CREATE POLICY "Allow public read access to depots" ON public.depots FOR SELECT USING (true);
CREATE POLICY "Allow public read access to buses" ON public.buses FOR SELECT USING (true);
CREATE POLICY "Allow public read access to routes" ON public.routes FOR SELECT USING (true);
CREATE POLICY "Allow public read access to route_stops" ON public.route_stops FOR SELECT USING (true);

-- PROFILES RLS
CREATE POLICY "Users view own profile" ON public.profiles FOR SELECT USING (true);
CREATE POLICY "Users insert own profile" ON public.profiles FOR INSERT WITH CHECK (true);
CREATE POLICY "Users update own profile" ON public.profiles FOR UPDATE USING (true);

-- COMPLAINTS RLS
CREATE POLICY "Users view own complaints" ON public.complaints FOR SELECT USING (true);
CREATE POLICY "Users create complaints" ON public.complaints FOR INSERT WITH CHECK (true);

CREATE POLICY "Depot heads view assigned complaints" ON public.complaints FOR SELECT USING (
    depot_id IN (
        SELECT depot_id FROM public.profiles 
        WHERE auth_user_id = auth.uid() AND role = 'DEPOT_HEAD'
    )
);

CREATE POLICY "Depot heads update assigned complaints" ON public.complaints FOR UPDATE USING (
    depot_id IN (
        SELECT depot_id FROM public.profiles 
        WHERE auth_user_id = auth.uid() AND role = 'DEPOT_HEAD'
    )
);

CREATE POLICY "Admins full access to complaints" ON public.complaints FOR ALL USING (
    EXISTS (
        SELECT 1 FROM public.profiles 
        WHERE auth_user_id = auth.uid() AND role = 'ADMIN'
    )
);

-- AUTOMATIC UPDATED_AT TRIGGER FUNCTION
CREATE OR REPLACE FUNCTION update_timestamp()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER update_profiles_modtime
    BEFORE UPDATE ON public.profiles
    FOR EACH ROW EXECUTE FUNCTION update_timestamp();

CREATE TRIGGER update_complaints_modtime
    BEFORE UPDATE ON public.complaints
    FOR EACH ROW EXECUTE FUNCTION update_timestamp();
